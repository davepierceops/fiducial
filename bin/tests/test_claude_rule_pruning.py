"""Contracts for the approved CLAUDE.md pruning rulings.

Boundary: contract-verified local source selection and generated bytes. The
baseline is the locally available Git object named in the human rulings;
these tests do not fetch it. Native loading, adherence, installed hooks and
forge enforcement are outside this contract (unverified/not-material here).
Pending retirements are projected out of selection using the reviewed
manifest, without inventing archive decision IDs. FIDUCIAL_PRUNING_ROOT may
instead name a prepared finalization preview. Neither projection proves
merge-time decision allocation, valid final archives, or installed state.
Once the manifest names a retirement decision, actual source selection and
archive references to that decision-log entry are checked without projection.
"""
from __future__ import annotations

import dataclasses
import io
import json
import os
import pathlib
import re
import subprocess
import tarfile
import tempfile
import unittest

from rulestore import query, terms
from rulestore.emit import blocks, targets
from rulestore.store import FileRowSource
from tests.helpers import REPO_ROOT
from tests.test_skill_context_extraction import inputs


BASELINE = "fb310dd9c1ea56e4fa2e1b9b671a50c128fdec0f"
MOVED = {
    "review-artifact": ["R0186"],
    "intake": ["R0763"],
    "change-flow": ["R1138", "R1614", "R1450", "R0011"],
    "gate": ["R0555"],
    "verification-checklists": ["R0030", "R0032", "R0033"],
}
SUCCESSORS = {
    **dict.fromkeys("R0174 R0179 R0455".split(), "R0172"),
    **dict.fromkeys("R0021 R0177 R0111 R0783 R0461 R0161 R0181 R0182 R0190 R0192 R0460".split(), "R0110"),
    "R0457": "R0193", "R0458": "R0166", "R0193": "R0170",
    **dict.fromkeys("R0536 R0562 R0572 R0573 R0490".split(), "R0534"),
    "R0017": "R1513",
}
REMOVED = set("""R0168 R0180 R0191 R0730 R0725 R0207 R0880 R0889 R0931
R0937 R1611 R1606 R1607 R0999 R1029 R1176 R0229 R0241 R0245 R0246
R0248a R0249 R0252 R0262 R1612 R0100 R0570 R0065 R0112 R0781 R0002
R0007 R0044""".split())


class TestClaudeRulePruning(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory(prefix="fiducial-pruning-contract-")
        cls.addClassCleanup(cls.tmp.cleanup)
        baseline = pathlib.Path(cls.tmp.name)
        archive = subprocess.run(["git", "archive", BASELINE, "rules", "process", "bin/hooks"],
                                 cwd=REPO_ROOT, check=True, capture_output=True).stdout
        with tarfile.open(fileobj=io.BytesIO(archive)) as stream:
            stream.extractall(baseline, filter="data")
        cls.old = inputs(baseline)
        cls.root = pathlib.Path(os.environ.get("FIDUCIAL_PRUNING_ROOT", str(REPO_ROOT)))
        cls.manifest = json.loads((cls.root / "docs/plans/claude-rule-pruning-finalization-20261105.json").read_text())
        cls.source = inputs(cls.root)
        cls.retirement_decision = cls.manifest["retirement_decision"]
        selected = cls.source.rows
        if cls.retirement_decision is None:
            selected = [r for r in selected if r.id not in cls.manifest["pending_retirements"]]
        cls.current = dataclasses.replace(cls.source, head=BASELINE, rows=selected)
        cls.old_rows = {r.id: r for r in cls.old.rows if r.kind == "rule"}
        cls.old_processes = {r.id: r for r in cls.old.rows if r.kind == "process"}
        cls.rows = {r.id: r for r in cls.current.rows if r.kind == "rule"}
        cls.processes = {r.id: r for r in cls.current.rows if r.kind == "process"}
        cls.emitted = {name: targets()[name].emit(cls.current) for name in ("claude-code", "codex")}

    def test_selection_contains_exactly_approved_retirements_and_preserves_sources(self):
        moved = {r for ids in MOVED.values() for r in ids}
        self.assertEqual(self.manifest["baseline"], BASELINE)
        self.assertEqual(set(self.manifest["pending_retirements"]), REMOVED | moved)
        self.assertEqual(self.manifest["moved_to_skill"], {r: skill for skill, ids in MOVED.items() for r in ids})
        self.assertEqual(set(self.old_rows) - set(self.rows), REMOVED | moved | set(SUCCESSORS))
        self.assertEqual(set(self.rows) - set(self.old_rows), set())
        source = FileRowSource(self.root)
        if self.retirement_decision is not None:
            self.assertRegex(self.retirement_decision, r"^DEC-\d{6}$")
            log = (self.root / "decisions/log.md").read_text()
            self.assertRegex(log, r"(?m)^## " + re.escape(self.retirement_decision) + r" — .+$")
            self.assertTrue(set(self.manifest["pending_retirements"]).isdisjoint(
                r.id for r in self.source.rows if r.kind == "rule"))
        for row_id in REMOVED | moved:
            path = self.root / "rules" / (row_id + ".md")
            if self.retirement_decision is not None:
                self.assertFalse(path.exists(), row_id + " must not remain live after finalization")
                path = self.root / "rules/retired" / (row_id + ".md")
            elif not path.exists():
                path = self.root / "rules/retired" / (row_id + ".md")
            self.assertTrue(path.is_file(), row_id)
            original = source._row(path, "rule")
            if self.retirement_decision is not None:
                self.assertEqual(original.keys.get("retired"), [self.retirement_decision.lower()], row_id)
            self.assertEqual(original.body, self.old_rows[row_id].body, row_id)
            for key in ("role", "session", "corpus", "condition"):
                self.assertEqual(original.keys.get(key), self.old_rows[row_id].keys.get(key), (row_id, key))
        for emission in self.emitted.values():
            for path, text in emission.files.items():
                if path in ("CLAUDE.md", "AGENTS.md") or "/agents/" in path:
                    for row_id in REMOVED:
                        self.assertNotIn(self.old_rows[row_id].body, text, (row_id, path))

    def test_moved_bodies_survive_in_skills_and_leave_all_roots_and_agents(self):
        for harness, emission in self.emitted.items():
            prefix = ".claude" if harness == "claude-code" else ".agents"
            standing = {p: text for p, text in emission.files.items()
                        if p in ("CLAUDE.md", "AGENTS.md") or "/agents/" in p}
            self.assertTrue(standing)
            for skill, ids in MOVED.items():
                skill_text = emission.files[prefix + "/skills/" + skill + "/SKILL.md"]
                for row_id in ids:
                    with self.subTest(harness=harness, row=row_id):
                        body = self.old_rows[row_id].body
                        self.assertIn(body, self.processes[skill].body)
                        self.assertIn(body, skill_text)
                        for path, text in standing.items():
                            self.assertNotIn(body, text, path)

    def test_consolidation_archive_bodies_and_successor_scope_unions(self):
        source = FileRowSource(self.root)
        for row_id, successor in SUCCESSORS.items():
            with self.subTest(row=row_id):
                self.assertNotIn(row_id, self.rows)
                archived = source._row(self.root / "rules/retired" / (row_id + ".md"), "rule")
                self.assertEqual(archived.keys["retired"], [successor.lower()])
                expected_body = self.old_rows[row_id].body
                if row_id == "R0193":
                    # The human first revised this row, then consolidated it.
                    expected_body = "When a fact changes, update its current references and report any you cannot update. Preserve historical records."
                self.assertEqual(archived.body, expected_body)
                for key in ("role", "session", "corpus", "condition"):
                    self.assertEqual(archived.keys.get(key), self.old_rows[row_id].keys.get(key))
        for successor in ("R0172", "R0110", "R0166", "R1513", "R0534"):
            originals = [successor] + [r for r, target in SUCCESSORS.items() if target == successor]
            for key in ("role", "session", "corpus"):
                expected = set().union(*(set(self.old_rows[r].keys.get(key) or []) for r in originals))
                self.assertEqual(set(self.rows[successor].keys.get(key) or []), expected, (successor, key))
        self.assertFalse(self.rows["R0534"].keys.get("condition"))
        self.assertEqual(self.rows["R1513"].keys["verb"], ["require"])

    def test_moved_instructions_reach_every_original_role_corpus_session(self):
        for skill in MOVED:
            for key in ("role", "corpus", "session"):
                originals = [self.old_processes[skill]] + [self.old_rows[r] for r in MOVED[skill]]
                expected = set().union(*(set(r.keys.get(key) or []) for r in originals))
                self.assertEqual(set(self.processes[skill].keys.get(key) or []), expected, (skill, key))
            for row_id in MOVED[skill]:
                old = self.old_rows[row_id]
                for role in old.keys["role"]:
                    for corpus in old.keys["corpus"]:
                        for session in old.keys["session"]:
                            where = {"role": role, "corpus": corpus, "session": session}
                            with self.subTest(row=row_id, **where):
                                selected = query.select(self.current.rows, where, self.current.sequences)
                                self.assertIn(skill, {r.id for r in selected if r.kind == "process"})
                                bundle = targets()["bundle"].emit(dataclasses.replace(self.current, where=where))
                                self.assertIn(old.body, next(iter(bundle.files.values())))

    def test_software_obligations_keep_explicit_scopes_when_skills_reach_writing(self):
        verification = self.processes["verification-checklists"].body
        self.assertIn("Sections apply to software unless they explicitly include writing", verification)
        self.assertIn("Applies to all roles in software and writing", verification)
        release_section = verification[verification.index("## Release-impact labels"):]
        label_position = release_section.index(self.old_rows["R0030"].body)
        self.assertIn("At the release decision", release_section[:label_position])
        change = self.processes["change-flow"].body
        build = change.index("1. **Spec.**")
        # The build/release sequence needs its own software scope after the
        # reconciliation paragraph that explicitly applies to both corpora.
        reconciliation = change.index(self.old_rows["R0011"].body) + len(self.old_rows["R0011"].body)
        self.assertIn("software", change[reconciliation:build].lower())
        self.assertIn("role scopes stated below", change)
        self.assertIn("For the Chief of Staff, Writer, Copy Editor, and Critic", change)

    def test_prose_stripping_preserves_enforcement_configuration_and_scripts(self):
        for row_id in ("R0196", "R0564"):
            with self.subTest(row=row_id):
                self.assertIn(row_id, self.rows)
                before, old_prose = blocks.parse(self.old_rows[row_id].body)
                after, prose = blocks.parse(self.rows[row_id].body)
                self.assertTrue(before)
                self.assertEqual(after, before)
                self.assertEqual(prose, "")
                self.assertEqual(self.rows[row_id].keys["enforce"], self.old_rows[row_id].keys["enforce"])
                for harness, emission in self.emitted.items():
                    for path, text in emission.files.items():
                        if path in ("CLAUDE.md", "AGENTS.md") or "/agents/" in path:
                            self.assertNotIn(old_prose, text, (harness, path))
        self.assertIn("R0564", self.processes["project-setup"].body)
        for harness, emission in self.emitted.items():
            old = targets()[harness].emit(self.old)
            paths = {p for p in old.files if "/hooks/" in p or p.endswith(("settings.json", "hooks.json"))}
            self.assertTrue(paths)
            for path in paths:
                self.assertEqual(emission.files.get(path), old.files[path], (harness, path))
            self.assertEqual(emission.executable, old.executable)

    def test_skill_dependencies_are_available_without_incidental_root_terms(self):
        for harness, emission in self.emitted.items():
            prefix = ".claude" if harness == "claude-code" else ".agents"
            root = emission.files["CLAUDE.md" if harness == "claude-code" else "AGENTS.md"]
            for skill in (*MOVED, "command-blocks"):
                available = root + emission.files[prefix + "/skills/" + skill + "/SKILL.md"]
                for definition in terms.pull_definitions([self.processes[skill]], self.current.rows):
                    self.assertIn(definition.body, available, (harness, skill, definition.id))


if __name__ == "__main__":
    unittest.main()
